import { createRequire } from 'node:module'; const { chromium } = createRequire(process.cwd() + '/')('playwright');
const { buildPushPayload } = await import(process.cwd() + '/supabase/functions/send-food-club-push/logic.js');
const BASE = process.env.PWA_BASE || 'http://127.0.0.1:5190';
const out = []; const ok = (n, c, e = '') => out.push(`${c ? 'PASS' : 'FAIL'}  ${n}${e ? '  — ' + e : ''}`);
const browser = await chromium.launch(process.env.PW_CHANNEL ? { channel: process.env.PW_CHANNEL } : {});
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
await ctx.grantPermissions(['notifications'], { origin: BASE });
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await cdp.send('ServiceWorker.enable');
const regs = [];
cdp.on('ServiceWorker.workerRegistrationUpdated', (e) => regs.push(...e.registrations));
await page.goto(`${BASE}/kitchen/club`);
const swOk = await page.evaluate(async () => { const r = await Promise.race([navigator.serviceWorker.ready, new Promise((res) => setTimeout(() => res(null), 8000))]); return r ? r.scope : null; });
ok('service worker registrato e attivo', !!swOk, swOk || 'nessuno');
const man = await cdp.send('Page.getAppManifest');
ok('manifest senza errori di parsing', man.errors.length === 0, `${man.url} ${man.errors.map((x) => x.message).join(';')}`);
const parsed = JSON.parse(man.data || '{}');
ok('manifest: start_url/scope/display', !!parsed.start_url && parsed.display === 'standalone', `start_url=${parsed.start_url} scope=${parsed.scope} display=${parsed.display}`);
const inst = await cdp.send('Page.getInstallabilityErrors');
ok('installabile (Chrome, nessun errore di installabilità)', inst.installabilityErrors.length === 0, inst.installabilityErrors.map((e) => e.errorId).join(','));
await page.waitForTimeout(500);
const reg = regs.find((r) => r.scopeURL.startsWith(BASE) && !r.isDeleted);
const payload = buildPushPayload({ kind: 'voucher_unlocked', title: '5,00 € SBLOCCATI', body: 'Il tuo buono è pronto fino al 04/12.', url: '/kitchen/club/buoni' });
await cdp.send('ServiceWorker.deliverPushMessage', { origin: BASE, registrationId: reg.registrationId, data: JSON.stringify(payload) });
await page.waitForTimeout(1500);
const notes = await page.evaluate(async () => (await (await navigator.serviceWorker.ready).getNotifications()).map((n) => ({ title: n.title, body: n.body, tag: n.tag, data: n.data })));
const n = notes.find((x) => x.tag === 'food-club-voucher_unlocked');
ok('push Club consegnato al SW -> notifica mostrata', !!n, JSON.stringify(notes));
ok('notifica: url verso /kitchen/club/buoni', n?.data?.url === '/kitchen/club/buoni', JSON.stringify(n?.data));
// stesso tipo: sostituisce (tag) — seconda push
await cdp.send('ServiceWorker.deliverPushMessage', { origin: BASE, registrationId: reg.registrationId, data: JSON.stringify(buildPushPayload({ kind: 'voucher_unlocked', title: 'SECONDO', body: 'x', url: '/kitchen/club/buoni' })) });
await page.waitForTimeout(1000);
const notes2 = await page.evaluate(async () => (await (await navigator.serviceWorker.ready).getNotifications({ tag: 'food-club-voucher_unlocked' })).map((n) => n.title));
ok('stesso tipo: la notifica precedente viene sostituita', notes2.length === 1 && notes2[0] === 'SECONDO', JSON.stringify(notes2));
// regressione: payload "ordine pronto" invariato
await cdp.send('ServiceWorker.deliverPushMessage', { origin: BASE, registrationId: reg.registrationId, data: JSON.stringify({ orderId: 'o-123', title: 'PRONTO', body: 'vieni', url: '/kitchen/status?order=o-123' }) });
await page.waitForTimeout(1000);
const notes3 = await page.evaluate(async () => (await (await navigator.serviceWorker.ready).getNotifications({ tag: 'kitchen-order-o-123' })).map((n) => n.data.url));
ok('regressione: push "ordine pronto" invariata (tag kitchen-order-<id>)', notes3[0] === '/kitchen/status?order=o-123', JSON.stringify(notes3));
console.log(out.join('\n'));
await browser.close();
